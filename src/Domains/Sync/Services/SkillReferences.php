<?php

namespace LaRecipe\Domains\Sync\Services;

use LaRecipe\Domains\Markdown\Components\ComponentDefinition;
use LaRecipe\Domains\Markdown\Components\ComponentRegistry;

/**
 * The skill references that describe this app's docs dialect, generated from
 * the code instead of written by hand: the component catalog from the
 * component registry (built-ins and the host's own components) and the
 * manifest, navigation and frontmatter references from the JSON Schemas.
 *
 * Generated, so a skill never tells an agent about a component or a key that
 * does not exist. When a schema file is not there yet, a short built-in
 * description of the same keys is used instead.
 */
final class SkillReferences
{
    public const GENERATED_NOTICE = '<!-- Generated by php artisan larecipe:agents. Do not edit: run the command again instead. -->';

    /** Which generated reference each skill carries. */
    public const MAP = [
        'larecipe-write-docs' => ['components.md', 'frontmatter.md', 'manifest.md', 'navigation.md'],
        'larecipe-update-docs' => ['components.md', 'frontmatter.md'],
        'larecipe-audit-docs' => ['components.md', 'frontmatter.md', 'manifest.md', 'navigation.md'],
        'larecipe-upgrade-v2' => ['components.md', 'frontmatter.md', 'manifest.md', 'navigation.md'],
    ];

    public function __construct(
        private readonly ComponentRegistry $components,
        private readonly string $schemas,
    ) {}

    /** @return array<string, array<string, string>> skill name => [file name => contents] */
    public function generate(): array
    {
        $files = [
            'components.md' => $this->components(),
            'frontmatter.md' => $this->frontmatter(),
            'manifest.md' => $this->manifest(),
            'navigation.md' => $this->navigation(),
        ];

        $generated = [];

        foreach (self::MAP as $skill => $names) {
            foreach ($names as $name) {
                $generated[$skill][$name] = $files[$name];
            }
        }

        return $generated;
    }

    private function components(): string
    {
        $lines = [
            self::GENERATED_NOTICE,
            '',
            '# Components',
            '',
            'Every component this app\'s docs can use. Anything else renders as escaped text and fails `php artisan larecipe:validate`.',
            '',
            '- Write a component as a PascalCase tag on its own line: `<Callout type="warning">`, content on the next lines, then `</Callout>`. A component without content closes itself: `<Name prop="value" />`.',
            '- `:::callout` directives produce the same component, if you prefer that syntax.',
            '- Props are strings. Write booleans as `prop="true"` or `prop="false"` and lists or objects as JSON strings. There are no JSX expressions.',
            '- Prefer GitHub alerts (`> [!NOTE]`, `> [!TIP]`, `> [!WARNING]`) for simple callouts: they read well on GitHub too.',
            '',
        ];

        foreach ($this->components->all() as $definition) {
            if ($definition->chromeOnly) {
                continue;
            }

            array_push($lines, ...$this->component($definition));
        }

        return implode("\n", $lines)."\n";
    }

    /** @return list<string> */
    private function component(ComponentDefinition $definition): array
    {
        $origin = match ($definition->origin) {
            'builtin' => 'built in',
            'host' => 'defined by this app',
            default => $definition->origin,
        };

        $lines = ["## {$definition->name}", ''];

        if ($definition->description !== null && $definition->description !== '') {
            $lines[] = rtrim($definition->description, '.').". ({$origin})";
        } else {
            $lines[] = "({$origin})";
        }

        $lines[] = '';

        if ($definition->props !== []) {
            $lines[] = '| Prop | Type | Required | Default | Allowed values | Description |';
            $lines[] = '| --- | --- | --- | --- | --- | --- |';

            foreach ($definition->props as $name => $spec) {
                $lines[] = sprintf(
                    '| `%s` | %s | %s | %s | %s | %s |',
                    $name,
                    (string) ($spec['type'] ?? 'string'),
                    ($spec['required'] ?? false) ? 'yes' : 'no',
                    array_key_exists('default', $spec) ? '`'.$this->scalar($spec['default']).'`' : '',
                    isset($spec['enum']) ? implode(', ', array_map(fn ($v) => '`'.$this->scalar($v).'`', (array) $spec['enum'])) : '',
                    $this->cell((string) ($spec['description'] ?? '')),
                );
            }

            $lines[] = '';
        }

        return [...$lines, '```markdown', ...$this->example($definition), '```', ''];
    }

    /** @return list<string> */
    private function example(ComponentDefinition $definition): array
    {
        $props = '';

        foreach ($definition->props as $name => $spec) {
            if (($spec['required'] ?? false) || isset($spec['enum'])) {
                $value = isset($spec['enum']) ? ($spec['default'] ?? ((array) $spec['enum'])[0]) : '...';
                $props .= ' '.$name.'="'.$this->scalar($value).'"';
            }
        }

        return ["<{$definition->name}{$props}>", 'Content in Markdown.', "</{$definition->name}>"];
    }

    private function frontmatter(): string
    {
        $schema = $this->schema('frontmatter.schema.json');

        $intro = [
            self::GENERATED_NOTICE,
            '',
            '# Frontmatter',
            '',
            'YAML at the top of a page configures that page only. Set-level settings belong in `larecipe.json`, navigation in `navigation.json`. Values for your own components go under `meta:` (they read them as `page.meta`). Other unknown keys are allowed but never reach readers, and `larecipe:validate` warns about likely typos.',
            '',
            'Every page should have `title`, `description` and `sources`. `sources` lists the code the page documents (globs from the project root, optionally `path#region`), so `php artisan larecipe:affected` can tell when the page goes stale.',
            '',
        ];

        if ($schema !== null) {
            return implode("\n", [...$intro, ...$this->schemaTable($schema), '', $this->frontmatterExample()])."\n";
        }

        $rows = [
            ['title', 'string', 'The page title. Required unless the first `# H1` provides it.'],
            ['description', 'string', 'One sentence. Used by llms.txt, search snippets, meta tags and the MCP `list_pages` tool.'],
            ['sources', 'list of strings', 'Code this page documents: `app/Billing/**`, `routes/billing.php`, `routes/api.php#billing`.'],
            ['order', 'integer', 'Sort order in zero-config navigation (lower first).'],
            ['icon', 'string', 'A Lucide icon name for navigation.'],
            ['tags', 'list of strings', 'Search tags.'],
            ['badge', 'object', '`{ label: "New", tone: "info" }` shown next to the title in navigation.'],
            ['since', 'string', 'The version that introduced the feature.'],
            ['deprecated', 'boolean', 'Marks the page as deprecated.'],
            ['hidden', 'boolean', 'Routable but left out of navigation.'],
            ['noindex', 'boolean', 'Asks search engines not to index the page.'],
            ['visibility', 'public or private', 'Private pages are checked by the `viewLarecipe` gate on every surface.'],
            ['redirect_from', 'list of strings', 'Old URLs that redirect here.'],
            ['layout', 'default, wide or full', 'Page layout.'],
            ['inserts', 'object or false', 'Opt out of site-wide insert points: `{ article.after: false }`, or `false` for all.'],
            ['type', 'page or openapi', 'Page type.'],
        ];

        $lines = [...$intro, '| Key | Type | Meaning |', '| --- | --- | --- |'];

        foreach ($rows as [$key, $type, $meaning]) {
            $lines[] = "| `{$key}` | {$type} | {$meaning} |";
        }

        return implode("\n", [...$lines, '', $this->frontmatterExample()])."\n";
    }

    private function frontmatterExample(): string
    {
        return implode("\n", [
            '```yaml',
            '---',
            'title: Webhooks',
            'description: Receive signed events from the app and verify them.',
            'sources: ["app/Webhooks/**", "routes/webhooks.php"]',
            'order: 20',
            '---',
            '```',
        ]);
    }

    private function manifest(): string
    {
        $schema = $this->schema('larecipe.schema.json');
        $intro = [
            self::GENERATED_NOTICE,
            '',
            '# The set manifest: larecipe.json',
            '',
            'One `larecipe.json` per doc set, at the root of its content. It holds presentation and content structure only. Infrastructure (routes, the driver, cache, AI) lives in `config/larecipe.php`, and secrets live nowhere in the docs.',
            '',
        ];

        if ($schema !== null) {
            return implode("\n", [...$intro, ...$this->schemaTable($schema)])."\n";
        }

        $rows = [
            ['$schema', 'The schema URL, for editors and agents.'],
            ['name', 'The docs site name.'],
            ['description', 'One sentence about the product.'],
            ['logo', 'A path, or `{ light, dark }`.'],
            ['favicon', 'A path.'],
            ['repository', '`{ url, branch, docsPath }` for edit links.'],
            ['theme', '`{ accent, radius, fonts: { sans, mono }, mode }`.'],
            ['versions', 'A list of `{ id, label, status, default, visibility }`. Omit for an unversioned set.'],
            ['locales', 'A list of `{ code, label, dir, default }`.'],
            ['landing', 'The landing page path.'],
            ['navbar', '`{ links: [{ label, href }], cta: { label, href } }`.'],
            ['redirects', 'A list of `{ from, to, status }`.'],
            ['assets', '`{ css: ["theme.css"] }`.'],
            ['inserts', 'Components placed at named insert points: `{ "article.after": ["Subscribe"] }`.'],
            ['integrations', 'Analytics integrations: GA4, Plausible, Fathom, PostHog or a custom script. Repository sets only; a database set sets them in config/larecipe.php.'],
            ['agents', '`{ llmsTxt: { description, instructions }, skillMd, context7 }`.'],
            ['provenance', 'Show who and what last changed each page (default true).'],
        ];

        $lines = [...$intro, '| Key | Meaning |', '| --- | --- |'];

        foreach ($rows as [$key, $meaning]) {
            $lines[] = "| `{$key}` | {$meaning} |";
        }

        return implode("\n", $lines)."\n";
    }

    private function navigation(): string
    {
        $schema = $this->schema('navigation.schema.json');
        $lines = [
            self::GENERATED_NOTICE,
            '',
            '# Navigation: navigation.json',
            '',
            'Optional, one per version, next to that version\'s pages. Without it, navigation is derived from folders and frontmatter `order`. `php artisan larecipe:navigation:freeze` writes the derived tree to a file when a team wants explicit control.',
            '',
            'Page entries are paths without `.md`, relative to the version root. A group is `{ "group": "Label", "pages": [...] }`, and groups nest. An external link is `{ "label": "...", "href": "https://..." }`.',
            '',
            '```json',
            '{',
            '  "tabs": [',
            '    {',
            '      "label": "Guides",',
            '      "groups": [',
            '        { "group": "Get started", "pages": ["index", "installation"] },',
            '        { "group": "Billing", "pages": ["billing/overview", { "group": "Webhooks", "pages": ["billing/webhooks"] }] }',
            '      ]',
            '    }',
            '  ]',
            '}',
            '```',
            '',
            'A single tab may be written as `{ "groups": [...] }`. When you add a page to a set that has a `navigation.json`, add it there too; with zero-config navigation, set `order` in its frontmatter instead.',
        ];

        if ($schema !== null) {
            array_push($lines, '', '## Keys', '', ...$this->schemaTable($schema));
        }

        return implode("\n", $lines)."\n";
    }

    private function schema(string $file): ?array
    {
        $path = rtrim($this->schemas, '/').'/'.$file;

        if (! is_file($path)) {
            return null;
        }

        $schema = json_decode((string) file_get_contents($path), true);

        return is_array($schema) ? $schema : null;
    }

    /** @return list<string> a Markdown table of a schema's properties, nested objects as dotted keys */
    private function schemaTable(array $schema): array
    {
        $lines = ['| Key | Type | Meaning |', '| --- | --- | --- |'];

        foreach ($this->properties($schema, $schema, '', 0) as [$key, $type, $meaning]) {
            $lines[] = "| `{$key}` | {$type} | {$meaning} |";
        }

        return $lines;
    }

    /** @return list<array{0: string, 1: string, 2: string}> */
    private function properties(array $node, array $root, string $prefix, int $depth): array
    {
        $node = $this->dereference($node, $root);
        $rows = [];

        foreach ((array) ($node['properties'] ?? []) as $name => $property) {
            if (! is_array($property)) {
                continue;
            }

            $property = $this->dereference($property, $root);
            $key = $prefix === '' ? (string) $name : $prefix.'.'.$name;
            $meaning = $this->cell((string) ($property['description'] ?? ''));

            if (isset($property['enum'])) {
                $meaning = trim($meaning.' One of: '.implode(', ', array_map(fn ($v) => '`'.$this->scalar($v).'`', (array) $property['enum'])).'.');
            }

            $rows[] = [$key, $this->type($property, $root), $meaning];

            if ($depth < 2 && isset($property['properties'])) {
                array_push($rows, ...$this->properties($property, $root, $key, $depth + 1));
            }
        }

        return $rows;
    }

    private function type(array $property, array $root): string
    {
        $type = $property['type'] ?? null;

        if (is_array($type)) {
            return implode(' or ', $type);
        }

        if ($type === 'array' && is_array($property['items'] ?? null)) {
            return 'list of '.$this->type($this->dereference($property['items'], $root), $root);
        }

        if ($type === null && (isset($property['oneOf']) || isset($property['anyOf']))) {
            $options = array_map(fn ($option) => is_array($option) ? $this->type($this->dereference($option, $root), $root) : 'any', (array) ($property['oneOf'] ?? $property['anyOf']));

            return implode(' or ', array_unique($options));
        }

        return is_string($type) ? $type : 'any';
    }

    private function dereference(array $node, array $root): array
    {
        $ref = $node['$ref'] ?? null;

        if (! is_string($ref) || ! str_starts_with($ref, '#/')) {
            return $node;
        }

        $target = $root;

        foreach (explode('/', substr($ref, 2)) as $segment) {
            $target = is_array($target) ? ($target[$segment] ?? null) : null;
        }

        return is_array($target) ? $target + array_diff_key($node, ['$ref' => true]) : $node;
    }

    private function scalar(mixed $value): string
    {
        return is_bool($value) ? ($value ? 'true' : 'false') : (is_scalar($value) ? (string) $value : (string) json_encode($value));
    }

    private function cell(string $text): string
    {
        return str_replace(['|', "\n"], ['\|', ' '], trim($text));
    }
}
